export const PROTOCOL_CATEGORIES = [
  "Bridge",
  "Chain",
  "DeFi",
  "DEX",
  "Info",
  "Launchpad",
  "Lending",
  "Meme",
  "Mini App",
  "Prediction Market",
  "Rewards",
  "RWA",
  "Stables",
  "Staking",
  "Wallet",
  "Yield",
  "Other",
] as const;

export type ProtocolCategory = typeof PROTOCOL_CATEGORIES[number];

export interface Protocol {
  id: number;
  name: string;
  /** Resolved display category: reviewed override > explicit chain > mapped
   * DeFiLlama category > Other. Consumers must not infer their own classification.
   */
  category: ProtocolCategory;
  /** Reviewed exception; unlike category, this is never generated by the updater. */
  categoryOverride?: {
    category: ProtocolCategory;
    reason: string;
    source: string;
  };
  symbol?: string;
  listedAt: number;
  referralUrl?: string;
  portfolioUrl: string;
  /** Reviewed active claim programme; never implies eligibility for a specific wallet.
   * For projects without claimSeasons. Missing/false disables claim promotion.
   * Adapters must not override this field.
   */
  claimAvailable?: boolean;
  /** Exclusive promotion deadline, UTC ISO timestamp (YYYY-MM-DDTHH:mm:ssZ).
   * Omit only when no deadline is known. Invalid values disable promotion.
   */
  claimEndsAt?: string;
  /** Optional reviewed claim destination; portfolioUrl is the fallback. */
  claimUrl?: string;
  /** Season-specific programmes. When present, replaces project-wide availability.
   * Keys are season labels (e.g. "Season 2"); unknown seasons stay unavailable.
   */
  claimSeasons?: Record<
    string,
    { claimAvailable?: boolean; claimUrl?: string; claimEndsAt?: string }
  >;
  module: string;
  defillama?: {
    isChain?: boolean;
    slug: string;
    /** Exact upstream category, not the normalized Checkpoint display category. */
    category?: string;
    description: string;
    logo: string | null;
    twitter?: string;
    url: string;
  };
}
